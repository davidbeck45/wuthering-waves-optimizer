// Wuthering Tools+ — generates src/sim/share/tacetIds.ts: Tacet Lab's game-id catalogue ids mapped to this app's
// character and weapon keys, so a Tacet Lab card (a `TacetLabCard` PNG chunk, src/sim/share/buildCodec.ts) can be
// read. Tacet Lab (https://github.com/DJ12421/Tacet-Lab, GPL-3.0) names characters and weapons by in-game id; the
// app keys them by name. Only ids that land on a character or weapon THIS app lists are written, so nothing the app
// does not ship can come in through the table.
//
//   npx tsx scripts/share-tacet-ids.ts <dir holding Tacet Lab's character-summaries.generated.ts and
//                                       weapon-summaries.generated.ts> [<tacet commit>]
//
// The two files are read as data (the JSON array after `=`), never executed.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { allCharactersList } from "../src/characters/characters";
import { getWeaponsByType } from "../src/weapons/weapons";

const dir = process.argv[2];
const commit = process.argv[3] ?? "unknown";
if (!dir) {
  console.error("usage: npx tsx scripts/share-tacet-ids.ts <tacet game-data dir> [commit]");
  process.exit(2);
}

const readArray = (file: string): Array<Record<string, unknown>> => {
  const text = readFileSync(join(dir, file), "utf8");
  return JSON.parse(text.slice(text.indexOf("=[") + 1)) as Array<Record<string, unknown>>;
};
const norm = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]/g, "");

const characters = readArray("character-summaries.generated.ts");
const weapons = readArray("weapon-summaries.generated.ts");

const appCharacters = new Map(allCharactersList.map((c) => [norm(c.name), c.key]));
const roverKey = (element: string, gender: string): string | undefined => {
  const keys = allCharactersList.map((c) => c.key);
  const want = norm(`rover${element}${gender}`);
  return keys.find((k) => norm(k) === want);
};

const characterIds: Record<string, string> = {};
const unmatchedCharacters: string[] = [];
for (const c of characters) {
  const id = String(c.id);
  const name = String(c.name);
  const rover = /^Rover: (\w+)$/.exec(name);
  const key = rover ? roverKey(rover[1], String(c.gender ?? "")) : appCharacters.get(norm(name));
  if (key) characterIds[id] = key;
  else unmatchedCharacters.push(`${id} ${name}`);
}

const appWeapons = new Map<string, string>();
for (const type of ["Swords", "Broadblades", "Pistols", "Rectifiers", "Gauntlets"]) {
  const list = getWeaponsByType(type) as unknown as Record<string, Array<{ key: string; name: string }>>;
  for (const bucket of Object.values(list)) for (const w of bucket) appWeapons.set(norm(w.name), w.key);
}
const weaponIds: Record<string, string> = {};
const unmatchedWeapons: string[] = [];
for (const w of weapons) {
  const key = appWeapons.get(norm(String(w.name)));
  if (key) weaponIds[String(w.id)] = key;
  else unmatchedWeapons.push(`${w.id} ${w.name}`);
}

const sorted = (o: Record<string, string>): Record<string, string> =>
  Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const out = `// GENERATED by scripts/share-tacet-ids.ts from Tacet Lab ${commit} (https://github.com/DJ12421/Tacet-Lab, GPL-3.0):
// its in-game catalogue ids -> this app's character / weapon keys, matched by name (Rover by element + gender).
// Only ids that land on something this app lists are kept. Do not edit by hand; re-run the script.
// Unmatched on generation: ${unmatchedCharacters.length} characters, ${unmatchedWeapons.length} weapons.

export const TACET_CHARACTER_IDS: Record<string, string> = ${JSON.stringify(sorted(characterIds), null, 2)};

export const TACET_WEAPON_IDS: Record<string, string> = ${JSON.stringify(sorted(weaponIds), null, 2)};
`;
const target = resolve(import.meta.dirname ?? ".", "../src/sim/share/tacetIds.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${Object.keys(characterIds).length} characters, ${Object.keys(weaponIds).length} weapons`);
if (unmatchedCharacters.length) console.log("unmatched characters:", unmatchedCharacters.join(", "));
if (unmatchedWeapons.length) console.log("unmatched weapons:", unmatchedWeapons.join(", "));

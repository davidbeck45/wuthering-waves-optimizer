/** A worker in this thread: the same handler the solver worker runs, messages structured-cloned both ways. */
function inProcessWorker(engine: RileyEngine, sent: unknown[] = []): WorkerLike {
  const w: WorkerLike = {
    onmessage: null,
    onerror: null,
    postMessage(message) {
      sent.push(message);
      handle(structuredClone(message));
    },
    terminate() {},
  };
  const handle = createRileyHandler(engine, (msg) => setTimeout(() => w.onmessage?.({ data: structuredClone(msg) }), 0));
  return w;
}

